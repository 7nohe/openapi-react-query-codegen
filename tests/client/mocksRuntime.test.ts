// End to end: generate the client and the mocks, start MSW with the generated
// handlers, and call the API through the generated client. Nothing listens on
// the base URL, so every answer comes from a handler.

import { rm } from "node:fs/promises";
import path from "node:path";
import { HttpResponse } from "msw/http";
import { setupServer } from "msw/node";
import { afterAll, afterEach, beforeAll, describe, expect, test } from "vitest";
import { generate } from "../../src/generate.mjs";
import { inputPath } from "../utils";

const outputDir = path.join("tests", "client", "mocks-runtime-outputs");
const importDir = path.join(__dirname, "mocks-runtime-outputs");

// biome-ignore lint/suspicious/noExplicitAny: the modules are generated by the test
type Generated = any;

describe("generated handlers under MSW", () => {
  let sdk: Generated;
  let mocks: Generated;
  let server: ReturnType<typeof setupServer>;

  beforeAll(async () => {
    await generate(
      {
        input: inputPath("mocks.yaml"),
        output: outputDir,
        client: "fetch",
        pageParam: "page",
        nextPageParam: "nextPage",
        initialPageParam: "1",
        useDateType: true,
        mock: "msw",
      },
      "0.0.0-test",
      { silent: true },
    );
    const { client } = await import(
      path.join(importDir, "requests", "client.gen.ts")
    );
    client.setConfig({ baseUrl: "https://api.example.test/v1" });
    sdk = await import(path.join(importDir, "requests", "sdk.gen.ts"));
    mocks = await import(path.join(importDir, "mocks", "index.ts"));
    server = setupServer(...mocks.handlers);
    server.listen();
  }, 60_000);
  afterEach(() => server.resetHandlers());
  afterAll(async () => {
    server?.close();
    await rm(importDir, { recursive: true, force: true });
  });

  test("answers with the mock of the operation", async () => {
    const { data, response } = await sdk.getPet({ path: { "pet-id": "1" } });
    expect(response.status).toBe(200);
    expect(data).toEqual(mocks.getPetResponseMock());
    expect(data.name).toBe("Pochi");
  });

  test("dates travel as text and come back as Date objects", async () => {
    const { data } = await sdk.listPets();
    expect(data).toEqual([
      {
        id: 7,
        name: "Momo",
        status: "sold",
        bornAt: new Date("2020-05-17T09:00:00Z"),
      },
    ]);
  });

  test("a fixed path is not taken for a parameter", async () => {
    const { data } = await sdk.listMyPets();
    expect(Array.isArray(data)).toBe(true);
  });

  test("matches a path that has MSW's own syntax in it", async () => {
    expect((await sdk.countPets()).data).toBe(3);
    // The colon is part of the path and not a parameter: `/pets` is not it.
    expect(Array.isArray((await sdk.listPets()).data)).toBe(true);

    const file = await sdk.getFile({ path: { name: "a" } });
    expect(file.request.url).toBe(
      "https://api.example.test/v1/files/a.(json|yaml)/",
    );
    expect(file.data).toBe("string");

    const tag = await sdk.getTag({ path: { "1st": "x" } });
    expect(tag.data).toBe("string");
  });

  test("a parameter followed by text is not taken for the parameter alone", async () => {
    const archived = await sdk.archivePet({ path: { "pet-id": "1" } });
    expect(archived.response.status).toBe(202);
  });

  test("answers with the status of the response", async () => {
    const created = await sdk.createPet();
    expect(created.response.status).toBe(201);
    expect(created.data.name).toBe("Kuro");

    const deleted = await sdk.deletePet({ path: { "pet-id": "1" } });
    expect(deleted.response.status).toBe(204);

    const head = await sdk.headPets();
    expect(head.response.status).toBe(200);
  });

  test("answers text as text", async () => {
    const { data, response } = await sdk.getStatus();
    expect(response.headers.get("content-type")).toContain("text/plain");
    expect(data).toBe("ok");
  });

  test("a handler given a body answers with it", async () => {
    server.use(mocks.listPetsHandler([]));
    expect((await sdk.listPets()).data).toEqual([]);

    server.use(mocks.getPetHandler(mocks.petMock({ name: "Hachi" })));
    const { data } = await sdk.getPet({ path: { "pet-id": "1" } });
    expect(data.name).toBe("Hachi");
  });

  test("a handler given a resolver lets it answer", async () => {
    server.use(
      mocks.getPetHandler(({ params }: { params: { pet_id: string } }) =>
        HttpResponse.json(
          { message: `no pet ${params.pet_id}` },
          { status: 404 },
        ),
      ),
      mocks.deletePetHandler(() => new HttpResponse(null, { status: 409 })),
    );
    const found = await sdk.getPet({ path: { "pet-id": "42" } });
    expect(found.response.status).toBe(404);
    expect(found.error).toEqual({ message: "no pet 42" });

    const deleted = await sdk.deletePet({ path: { "pet-id": "1" } });
    expect(deleted.response.status).toBe(409);
  });
});
