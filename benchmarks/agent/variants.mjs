// The ways under test of telling an agent how to look an operation up in the
// generated client. Each variant adds files to a copy of the template project.
import { spawnSync } from "node:child_process";
import {
  chmodSync,
  copyFileSync,
  mkdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

const NAMES = `## Names

For an operation whose function is \`findPets\` (a GET) or \`addPet\` (any other method):

- \`queries/queries.ts\`: \`useFindPets(clientOptions?, queryKey?, options?)\` (useQuery) and \`useAddPet(mutationKey?, options?)\` (useMutation, called as \`mutate(clientOptions)\`)
- \`queries/suspense.ts\`: \`useFindPetsSuspense\`. \`queries/queryOptions.ts\`: \`findPetsOptions\`. \`queries/prefetch.ts\`: \`prefetchUseFindPets\`. \`queries/ensureQueryData.ts\`: \`ensureUseFindPetsData\`
- \`queries/common.ts\`: \`useFindPetsKey\` and \`UseFindPetsKeyFn(clientOptions?)\`, for \`invalidateQueries\`
- Import them from the \`queries\` directory. \`clientOptions\` is \`{ path, query, body, headers }\`.`;

const head = (dir) =>
  `# Generated API client

${dir} is generated by \`@7nohe/openapi-react-query-codegen\` from \`openapi.json\` (\`npm run codegen\`). Do not edit it. Its files are very large: look things up as described here instead of reading them.

${NAMES}`;

const grepGuide = (dir, prefix) => `${head(dir)}

## Finding an operation

- By URL path: \`grep -n -B1 'url: "/pets/{petId}"' ${prefix}requests/sdk.gen.ts\`. The line above the match starts with \`export const <function> =\`.
- By a word in its name: \`grep -o '^export const [A-Za-z0-9_]*' ${prefix}requests/sdk.gen.ts | grep -i pet\`

## What an operation takes and returns

- \`grep -n -A30 '^export type FindPetsData = ' ${prefix}requests/types.gen.ts\`: \`path\`, \`query\` and \`body\`
- \`grep -n -A12 '^export type FindPetsResponses = ' ${prefix}requests/types.gen.ts\`: the response for each status
- A schema one of them names: \`grep -n -A40 '^export type Pet = ' ${prefix}requests/types.gen.ts\`
`;

const cliGuide = (dir, prefix) => `${head(dir)}

## Finding an operation, and what it takes and returns

- \`npx openapi-rq --list <words>\`: the operations whose name, URL path or summary holds every word, one per line
- \`npx openapi-rq --describe <function>\`: its hooks, the type of \`clientOptions\`, the response for each status and the schemas they name
- A schema they name: \`grep -n -A40 '^export type Pet = ' ${prefix}requests/types.gen.ts\`
`;

const indexGuide = (dir, prefix) => `${head(dir)}

## Finding an operation, and what it takes and returns

\`${prefix}operations.jsonl\` has one line per operation: \`{"id","method","path","summary","hooks","request","response","errors","schemas"}\`. \`id\` is the function name, \`request\` is the type of \`clientOptions\` and \`response\` the response for each status.

- Find one: \`grep -i 'word' ${prefix}operations.jsonl | cut -c1-200\` (a line is long; cut it while searching)
- Read one: \`grep '"id":"findPets"' ${prefix}operations.jsonl\`
- A schema it names: \`grep -n -A40 '^export type Pet = ' ${prefix}requests/types.gen.ts\`
`;

const skill = `---
name: openapi-rq
description: Look up the generated API client in src/openapi (TanStack Query hooks generated from openapi.json). Use before calling, adding or changing any API call - it finds the operation for an endpoint and shows the hook to call, the type of its options and the response, without reading the very large generated files.
---

${cliGuide("`src/openapi`", "src/openapi/")}`;

function write(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}

/** Put the prototype CLI in place of the package's bin. */
function installCli(project) {
  const bin = join(project, "node_modules/.bin/openapi-rq");
  rmSync(bin, { force: true });
  writeFileSync(
    bin,
    '#!/usr/bin/env node\nawait import("../.orqc-proto/cli.mjs");\n',
  );
  chmodSync(bin, 0o755);
}

/** A guide in the generated directory, where an agent meets it on the way. */
function nested(project, guide) {
  write(join(project, "src/openapi/AGENTS.md"), guide("This directory", ""));
  write(join(project, "src/openapi/CLAUDE.md"), "@AGENTS.md\n");
}

/**
 * @typedef {object} Variant
 * @property {string} id
 * @property {string} label
 * @property {(project: string) => void} apply
 * @property {string[]} [flags] extra `claude` flags
 * @property {string[]} [allow] extra allowed tools
 */

/** @type {Variant[]} */
export const variants = [
  { id: "baseline", label: "nothing added", apply: () => {} },
  {
    id: "nested-grep",
    label: "guide in the output directory: grep recipes",
    apply: (project) => nested(project, grepGuide),
  },
  {
    id: "root-grep",
    label: "guide in the root CLAUDE.md: grep recipes",
    apply: (project) =>
      write(
        join(project, "CLAUDE.md"),
        grepGuide("`src/openapi`", "src/openapi/"),
      ),
  },
  {
    id: "nested-cli",
    label: "guide in the output directory: --list / --describe",
    apply: (project) => {
      nested(project, cliGuide);
      installCli(project);
    },
  },
  {
    id: "root-cli",
    label: "guide in the root CLAUDE.md: --list / --describe",
    apply: (project) => {
      write(
        join(project, "CLAUDE.md"),
        cliGuide("`src/openapi`", "src/openapi/"),
      );
      installCli(project);
    },
  },
  {
    id: "agents-md",
    label: "the package's own `--agentsMd`: a block in the root AGENTS.md",
    apply: (project) => {
      // The CLI of this checkout, as the template may hold an older release.
      const cli = join(here, "../../dist/cli.mjs");
      const run = spawnSync(
        process.execPath,
        [cli, "-i", "./openapi.json", "-o", "./src/openapi", "--agentsMd"],
        { cwd: project, encoding: "utf8" },
      );
      if (run.status !== 0) {
        throw new Error(`--agentsMd failed: ${run.stderr}`);
      }
    },
  },
  {
    id: "nested-index",
    label: "guide in the output directory: operations.jsonl",
    apply: (project) => {
      nested(project, indexGuide);
      copyFileSync(
        join(project, "node_modules/.orqc-proto/operations.jsonl"),
        join(project, "src/openapi/operations.jsonl"),
      );
    },
  },
  {
    id: "skill-cli",
    label: "Agent Skill: --list / --describe",
    apply: (project) => {
      write(join(project, ".claude/skills/openapi-rq/SKILL.md"), skill);
      installCli(project);
    },
  },
  {
    id: "mcp",
    label: "MCP server: search_operations / describe_operation",
    apply: (project) =>
      write(
        join(project, ".orqc-mcp.json"),
        `${JSON.stringify({
          mcpServers: {
            "openapi-rq": {
              command: "node",
              args: ["node_modules/.orqc-proto/mcp.mjs"],
            },
          },
        })}\n`,
      ),
    flags: ["--mcp-config", ".orqc-mcp.json"],
    allow: ["mcp__openapi-rq"],
  },
];

/** The prototype scripts every project copy carries in `node_modules`. */
export function installPrototypes(project, records) {
  const dir = join(project, "node_modules/.orqc-proto");
  mkdirSync(dir, { recursive: true });
  for (const file of ["cli.mjs", "mcp.mjs"]) {
    copyFileSync(join(here, "proto", file), join(dir, file));
  }
  copyFileSync(join(here, "records.mjs"), join(dir, "records.mjs"));
  writeFileSync(
    join(dir, "operations.jsonl"),
    `${records.map((record) => JSON.stringify(record)).join("\n")}\n`,
  );
}
